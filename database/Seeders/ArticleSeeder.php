    private function getCategories(): array
    {
        $query = $this->db->query("
            SELECT id, alias
            FROM categories
        ");

        $categories = [];

        foreach ($query->fetchAll(PDO::FETCH_ASSOC) as $category_id) {
            $categories[$category_id['alias']] = $category_id['id'];
        }

        return $categories;
    }
